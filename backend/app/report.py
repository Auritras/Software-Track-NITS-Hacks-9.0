"""Human-readable incident report (Markdown), generated from the analysis."""
from __future__ import annotations

from datetime import datetime

PRIORITY_LABEL = {"immediate": "Immediate", "short_term": "Short term", "long_term": "Long term"}


def _fmt_time(iso: str) -> str:
    return datetime.fromisoformat(iso).strftime("%Y-%m-%d %H:%M:%S UTC")


def _money(value: float) -> str:
    return f"₹{value:,.0f}"


def render_markdown(inc: dict) -> str:
    rc = inc["root_cause"]
    m = inc["impact"]["metrics"]
    lines = [
        f"# Incident Report - {inc['id']}",
        "",
        f"**{inc['title']}**",
        "",
        "| Field | Value |",
        "|---|---|",
        f"| Severity | {inc['severity']} |",
        f"| Status | {inc['status'].title()} |",
        f"| Started | {_fmt_time(inc['started_at'])} |",
        f"| Last event | {_fmt_time(inc['last_event_at'])} |",
        f"| Duration | {inc['duration_seconds']:.0f}s |",
        f"| Alerts correlated | {inc['alert_count']} alerts from {inc['service_count']} services |",
        "",
        "## Summary",
        "",
        inc["summary"],
        "",
        "## Event Correlation",
        "",
        *[f"- {line}" for line in inc["correlation"]["explanation"]],
        "",
        "## Root Cause",
        "",
        f"**{rc['label']}** (`{rc['service']}`) - {rc['cause_label']}, confidence **{rc['confidence']}%**.",
        "",
        "Why J.A.R.V.I.S. believes this:",
        "",
        *[f"- {e}" for e in rc["evidence"]],
        "",
        "Candidate ranking:",
        "",
        "| Service | Score | Coverage | Precedence | Depth | Causal signal |",
        "|---|---|---|---|---|---|",
        *[
            f"| {c['label']} | {c['score']:.2f} | {c['factors']['coverage']:.2f} | "
            f"{c['factors']['precedence']:.2f} | {c['factors']['depth']:.2f} | {c['factors']['causal']:.2f} |"
            for c in inc["candidates"]
        ],
        "",
        "## Impact",
        "",
        f"- Failed logins: **{m['failed_logins']:,}**",
        f"- Failed transactions: **{m['failed_transactions']:,}** ({_money(m['revenue_at_risk'])} at risk)",
        f"- Estimated users affected: **{m['users_affected']:,}**",
        f"- Capabilities impacted: {', '.join(inc['impact']['capabilities_impacted']) or 'n/a'}",
        "",
        "Affected services:",
        "",
        *[f"- {s['label']} - {s['capability']} ({s['events']} events, worst: {s['worst_severity']})"
          for s in inc["impact"]["affected_services"]],
    ]
    if inc["impact"]["at_risk_services"]:
        lines += ["", "At risk (depend on the root cause, not yet alerting):", "",
                  *[f"- {s['label']} - {s['capability']}" for s in inc["impact"]["at_risk_services"]]]
    lines += ["", "## Timeline", "", "| T+ | Service | Severity | Event |", "|---|---|---|---|"]
    for e in inc["timeline"]["events"]:
        if e["milestone"] or e["severity"] == "critical":
            msg = e["message"].replace("|", "\\|")
            lines.append(f"| {e['offset_seconds']:.0f}s | {e['service']} | {e['severity']} | {msg} |")
    lines += ["", "Propagation:", ""]
    for p in inc["timeline"]["propagation"]:
        hop = " (origin)" if p["is_root"] else f" via {p['via']}" if p["via"] else ""
        lines.append(f"- T+{p['offset_seconds']:.0f}s - {p['label']}{hop}")
    lines += ["", "## Recommended Actions", ""]
    for i, r in enumerate(inc["recommendations"], 1):
        lines.append(f"{i}. **[{PRIORITY_LABEL[r['priority']]}] {r['title']}** - {r['detail']}")
        if r.get("command"):
            lines.append(f"   ```\n   {r['command']}\n   ```")
    lines += ["", "---", "_Generated by J.A.R.V.I.S. - Justified Analysis, Reasoning & Visualization of Incident Systems_", ""]
    return "\n".join(lines)
